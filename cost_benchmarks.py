# 相近品种共用成本锚（仅当自身未单独配置时）
COST_ALIASES = {
    "CN:BC0": "CN:CU0",
}


def get_cost(instrument_id: str) -> dict | None:
    if instrument_id in COST_BENCHMARKS:
        return COST_BENCHMARKS[instrument_id]
    alias = COST_ALIASES.get(instrument_id)
    if alias and alias in COST_BENCHMARKS:
        return COST_BENCHMARKS[alias]
    return None


def cost_vs_price(instrument_id: str, price: float | None) -> dict | None:
    c = get_cost(instrument_id)
    if not c or price is None:
        return None
    primary = c["primary_cost"]
    cash = c["cash_cost"]
    high = c["comfort_high"]
    return {
        "unit": c["unit"],
        "label": c["label"],
        "primary_cost": primary,
        "cash_cost": cash,
        "comfort_high": high,
        "source": c["source"],
        "notes": [
            {"name": n[0], "value": n[1], "note": n[2]} for n in c.get("notes", [])
        ],
        "vs_primary_pct": (price / primary - 1) * 100 if primary else None,
        "vs_cash_pct": (price / cash - 1) * 100 if cash else None,
        "vs_high_pct": (price / high - 1) * 100 if high else None,
        "below_primary": price < primary,
        "below_cash": price < cash,
        "above_high": price > high,
        "position_vs_band": _band_position(price, cash, primary, high),
    }


def _band_position(price: float, cash: float, primary: float, high: float) -> str:
    if price < cash:
        return "低于现金成本"
    if price < primary:
        return "现金成本与完全成本之间"
    if price < high:
        return "完全成本与激励上沿之间"
    return "高于成本激励上沿"
